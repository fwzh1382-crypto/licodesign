#!/usr/bin/env python3
"""Build js/i18n-content.js from tools/translations.json and verify coverage.

    python3 tools/build_i18n.py            # build + check
    python3 tools/build_i18n.py --check    # check only

Any Persian string in the HTML that is not covered by either the global
data-i18n dictionary (js/main.js), the projects dictionary (js/projects.js),
or tools/translations.json is printed as MISSING. The build fails if any are
found, so a page can never silently fall back to untranslated Persian text in
English mode.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from i18n_scan import scan_all

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "translations.json"
OUT = ROOT / "js" / "i18n-content.js"
BANNER = ("/* Generated by tools/build_i18n.py — edit tools/translations.json, "
          "not this file. */\n"
          "/* LAICO DESIGN — fa -> en content map for static markup that has no\n"
          "   data-i18n key. Applied by js/main.js at runtime. */\n")


def main() -> int:
    translations = json.loads(SRC.read_text(encoding="utf-8"))
    found = scan_all(ROOT)
    missing = sorted(v for v in found if v not in translations)
    unused = sorted(v for v in translations if v not in found)

    print(f"translatable strings found : {len(found)}")
    print(f"translations provided      : {len(translations)}")
    print(f"missing                    : {len(missing)}")
    if missing:
        for m in missing:
            print("  MISSING " + repr(m))
    if unused:
        print(f"unused (kept for safety)   : {len(unused)}")

    if "--check" not in sys.argv:
        body = json.dumps(translations, ensure_ascii=False, indent=2, sort_keys=True)
        OUT.write_text(BANNER + "window.LAICO_T9N = " + body + ";\n", encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")

    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
